import { writeFileSync, readFileSync } from 'node:fs';
import { pptMasterReferences } from './ppt-master-reference.mjs';
const path = new URL('../editor-vuejs/src/lib/agent/ppt-master-references.mjs', import.meta.url);
const source = '// Generated by scripts/build-agent-references.mjs from the pinned upstream source.\nexport const pptMasterReferences = ' + JSON.stringify(pptMasterReferences) + ';\n';
if (process.argv.includes('--check')) {
  if (readFileSync(path, 'utf8').replaceAll('\r\n', '\n') !== source) throw new Error('Run node scripts/build-agent-references.mjs to update agent references.');
} else writeFileSync(path, source);
